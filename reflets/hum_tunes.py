"""Melodies with exact labels, in sixteenth-note slots (slot, length, semitones above the tonic): tunes most people know, and melodies HumTrans hardly has (chromatic notes, modes, syncopation, rests, repeats), for the synthetic eval and the hum test."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class Melody:
    name: str
    kind: str
    key: str
    notes: list[tuple[int, int, int]]
    meter: tuple[int, int] = (4, 4)

    @property
    def grid(self) -> int:
        return 2 if all(slot % 2 == 0 and length % 2 == 0 for slot, length, _ in self.notes) else 4

    @property
    def bars(self) -> int:
        numerator, denominator = self.meter
        return -(-max(slot + length for slot, length, _ in self.notes) // (16 * numerator // denominator))


